-- Restore SPLIT_BILL_DB_PROD_REHEARSAL and run direct comparative inventory
USE master;
SET NOCOUNT ON;

IF EXISTS (SELECT 1 FROM sys.databases WHERE name = 'SPLIT_BILL_DB_PROD_REHEARSAL')
BEGIN
    ALTER DATABASE SPLIT_BILL_DB_PROD_REHEARSAL SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE SPLIT_BILL_DB_PROD_REHEARSAL;
END;

RESTORE DATABASE SPLIT_BILL_DB_PROD_REHEARSAL
FROM DISK = 'C:\My_Project\TRIP_DISTRIBUTION\trip_split\backups\SPLIT_BILL_DB_Prod_Rehearsal.bak'
WITH REPLACE,
     MOVE 'SPLIT_BILL_DB' TO 'C:\Program Files\Microsoft SQL Server\MSSQL16.MSSQLSERVER\MSSQL\DATA\SPLIT_BILL_DB_PROD_REHEARSAL.mdf',
     MOVE 'SPLIT_BILL_DB_log' TO 'C:\Program Files\Microsoft SQL Server\MSSQL16.MSSQLSERVER\MSSQL\DATA\SPLIT_BILL_DB_PROD_REHEARSAL_log.ldf';

PRINT '=== REHEARSAL RESTORE COMPLETED ===';

-- Comparative Table Inventory
SELECT 
    p.TABLE_NAME,
    (SELECT COUNT(*) FROM SPLIT_BILL_DB.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = p.TABLE_NAME) AS ProdColCount,
    (SELECT COUNT(*) FROM SPLIT_BILL_DB_PROD_REHEARSAL.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = p.TABLE_NAME) AS RehColCount
FROM SPLIT_BILL_DB.INFORMATION_SCHEMA.TABLES p
WHERE p.TABLE_TYPE = 'BASE TABLE'
ORDER BY p.TABLE_NAME;

-- Comparative Row Counts
DECLARE @comp TABLE (TableName NVARCHAR(100), ProdRows INT, RehRows INT);
DECLARE @t NVARCHAR(100);
DECLARE cur CURSOR LOCAL FAST_FORWARD FOR 
    SELECT TABLE_NAME FROM SPLIT_BILL_DB.INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME;

OPEN cur;
FETCH NEXT FROM cur INTO @t;
WHILE @@FETCH_STATUS = 0
BEGIN
    DECLARE @pCnt INT, @rCnt INT;
    DECLARE @qp NVARCHAR(MAX) = N'SELECT @cnt = COUNT(*) FROM SPLIT_BILL_DB.dbo.[' + @t + '];';
    EXEC sp_executesql @qp, N'@cnt INT OUTPUT', @cnt = @pCnt OUTPUT;

    DECLARE @qr NVARCHAR(MAX) = N'SELECT @cnt = COUNT(*) FROM SPLIT_BILL_DB_PROD_REHEARSAL.dbo.[' + @t + '];';
    EXEC sp_executesql @qr, N'@cnt INT OUTPUT', @cnt = @rCnt OUTPUT;

    INSERT INTO @comp VALUES (@t, @pCnt, @rCnt);
    FETCH NEXT FROM cur INTO @t;
END
CLOSE cur;
DEALLOCATE cur;

SELECT 
    TableName,
    ProdRows,
    RehRows,
    (ProdRows - RehRows) AS RowDifference,
    CASE WHEN ProdRows = RehRows THEN 'MATCH' ELSE 'MISMATCH' END AS Status
FROM @comp
ORDER BY TableName;

SELECT 
    SUM(ProdRows) AS TotalProdRows, 
    SUM(RehRows) AS TotalRehRows 
FROM @comp;
